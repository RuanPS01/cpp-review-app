#include <iostream>

using namespace std;

int main (){
    
    double Numeros;
    int vet[100];
    double numeroX;
    int i;
    
    while (cin >> Numeros && Numeros != 0){
        
        for (i = 0; i < Numeros; i++){
            Numeros == vet[i];
        }
    }
    cin >> numeroX;
    
    if (numeroX != vet[i]){
        cout << numeroX << " encontrado na posicao " << vet[i] << endl;
    }
    
    
    return 0;
}