#include <iostream>
using namespace std;

int main(){
    int y;
    int x;

    
    double posicao[100];
    
    while(cin >> y && y != 0){
        y = posicao[100];
    }
    if(cin >> x && x == y){
        cout << x << " encontrado na posicao " << y << endl; 
    } else {
        cout << "Elemento nao encontrado";
    }
    return 0;
}
